"""Fits the rotor radiation tables used by the engine and writes Source/RotorDirectivity.h.

Input: the BEM results in results/ (made by horn.py and drum.py):
  results/horn_deflector.npz   python3 horn.py g-8h30 results/horn_deflector.npz
  results/horn_open.npz        python3 horn.py none   results/horn_open.npz
  results/drum.npz             python3 drum.py        results/drum.npz
Usage: python3 fit_directivity.py [out.h]      (needs numpy and scipy)

Steps
1. Power per third-octave band and angle, smoothed: horn +-15 deg (the axisymmetric model has an on-axis bright spot
   that a real, slightly asymmetric horn does not show; beyond 155 deg the value at 155 deg is kept), drum +-10 deg
   (front/back halves of the horizontal circle averaged, the drum is symmetric about its opening).
2. Normalisation per band: the mean power over the horizontal circle equals that of the previous hand-made model,
   so the diffuse-field tone of the instrument stays and only the directivity changes.
3. Fit: gains (dB) of in-phase Linkwitz-Riley bands per 5 deg step, least squares on a dense frequency grid with a
   smoothness penalty between neighbouring angles (no jumps when the rotor turns).
"""
import os, sys
import numpy as np
from scipy.optimize import least_squares

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, 'results')
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '..', 'Source', 'RotorDirectivity.h')
HORN_EDGES, DRUM_EDGES = [1250, 3150, 8000], [200, 400]


def smooth(P, th, width):
    ang = np.r_[-th[:0:-1], th]; PP = np.c_[P[:, :0:-1], P]
    out = np.zeros_like(P)
    for j, t in enumerate(th):
        m = np.abs(((ang - t + 180) % 360) - 180) <= width
        out[:, j] = PP[:, m].mean(1)
    return out


def load_horn(fn):
    D = np.load(fn); P = D['power'].copy(); th = np.round(D['theta']).astype(int); B = D['bands'].astype(float)
    j155 = int(np.where(th == 155)[0][0]); P[:, j155:] = P[:, [j155]]
    return B, th, smooth(P, th, 15)


def load_drum(fn):
    D = np.load(fn); P = D['power']; B = D['bands'].astype(float)
    th = np.arange(0, 181, 5)
    Ph = np.array([[(P[i][k // 5] + P[i][(72 - k // 5) % 72]) / 2 for k in th] for i in range(len(B))])
    return B, th, smooth(Ph, th, 10)


# previous hand-made patterns (power), only used for the per-band normalisation
def old_horn(c, f):
    u = 0.5 + 0.5 * c; lvl = 0.3 + 0.7 * u
    s2 = np.sqrt(1 - c * c + 0.0036) if c >= 0 else (np.sqrt(1.0036) + (2 - np.sqrt(1.0036)) * 0.5 * (1 - np.cos(np.pi * ((np.arccos(c) - np.pi / 2) / (np.pi / 2)))))
    fc = 343 / (np.pi * 0.045 * s2); fc = 1 / np.sqrt(np.sqrt(1 / fc ** 4 + 1 / 16000 ** 4))
    return lvl ** 2 / (1 + (f / fc) ** 2)


def old_drum(c, f):
    u = 0.5 + 0.5 * c; L = 1 / (1 + 1j * f / 200)
    return abs(L * (0.85 + 0.15 * u) + (1 - L) * (0.3 + 0.7 * u)) ** 2


def lr4bands(f, edges):
    """Magnitudes of the in-phase LR4 bands (they add up to 1), same tree as LRBandSplit in RotorRadiation.h."""
    out, carry = [], 1.0
    for e in edges:
        lp = 1 / (1 + (f / e) ** 4); out.append(carry * lp); carry *= 1 - lp
    out.append(carry); return np.array(out)


def fit(name, data, old, edges, lam=1.0):
    B, th, P = data; c = np.cos(np.radians(th)); na, nb = len(th), len(edges) + 1
    oldP = np.array([[old(ci, f) for ci in c] for f in B]); T = 10 * np.log10(P * (oldP.mean(1) / P.mean(1))[:, None])
    fd = np.geomspace(B[0] * 0.8, B[-1] * 1.15, 80)
    Td = np.array([np.interp(np.log(fd), np.log(B), T[:, j]) for j in range(na)])
    S = np.array([lr4bands(f, edges) for f in fd])

    def resid(x):
        G = x.reshape(na, nb); mag = np.einsum('fb,ab->af', S, 10 ** (G / 20))
        return np.r_[(20 * np.log10(mag) - Td).ravel(), lam * np.diff(G, axis=0).ravel()]
    G = least_squares(resid, np.zeros(na * nb), bounds=(-50, 15)).x.reshape(na, nb)
    Sc = np.array([lr4bands(f, edges) for f in B]); ec = 20 * np.log10(np.einsum('fb,ab->af', Sc, 10 ** (G / 20))) - T.T
    print(f'{name}: {nb} bands {edges}, error at band centres max {np.abs(ec).max():.1f} dB, median {np.median(np.abs(ec)):.2f} dB')
    return G


def table(name, G):
    rows = ['{' + ', '.join(f'{v:.2f}' for v in r) + '}' for r in G]
    lines = [', '.join(rows[i:i + 4]) for i in range(0, len(rows), 4)]
    return f'static const float {name}[{G.shape[0]}][{G.shape[1]}] = {{\n    ' + ',\n    '.join(lines) + '\n};\n'


HEAD = """// Wheelhouse - radiation of the rotating horn and the bass rotor, from boundary-element simulations
// (tools/acoustics: axisymmetric BEM of the 122 treble horn with / without deflector, 3D BEM of the bass rotor).
// Generated by tools/acoustics/fit_directivity.py - do not edit by hand.
//
// Model: each rotor's signal is split once into in-phase Linkwitz-Riley bands at *_EDGES (the bands add up to an
// all-pass, so changing their gains changes level only - no phase, hence no spurious pitch modulation). Every path
// mixes the bands with the gains for its angle between the rotor axis and the path (0 = mouth / opening towards the
// path, 180 = away). Rows: angle 0..180 in 5 degree steps, columns: band gains in dB, low to high. Normalised so that
// the mean power over the horizontal circle per third-octave equals the previous hand-made model: the diffuse-field
// tone stays, the directivity changes.
#pragma once
namespace rotary { namespace rotordir {

"""

if __name__ == '__main__':
    hd = fit('horn, deflector', load_horn(os.path.join(RES, 'horn_deflector.npz')), old_horn, HORN_EDGES)
    ho = fit('horn, open', load_horn(os.path.join(RES, 'horn_open.npz')), old_horn, HORN_EDGES)
    dr = fit('drum', load_drum(os.path.join(RES, 'drum.npz')), old_drum, DRUM_EDGES)
    s = HEAD
    s += 'static const float HORN_EDGES[3] = {' + ', '.join(str(e) for e in HORN_EDGES) + '};\n'
    s += 'static const float DRUM_EDGES[2] = {' + ', '.join(str(e) for e in DRUM_EDGES) + '};\n'
    s += table('HORN_DEFLECTOR', hd) + table('HORN_OPEN', ho) + table('DRUM', dr)
    s += '\n}} // namespace rotary::rotordir\n'
    open(OUT, 'w').write(s)
    print('wrote', os.path.normpath(OUT))
